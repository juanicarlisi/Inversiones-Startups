// «2 nov 1929» / «Nov 2, 1929»: corta, para que entre en la barra.
export const fechaCorta = (f) => {
  const d = f.getUTCDate(), m = MESES[idioma][f.getUTCMonth()], a = f.getUTCFullYear();
  return idioma === 'es' ? `${d} ${m} ${a}` : `${m} ${d}, ${a}`;
};
